// RSA-OAEP/SHA-256 encryption with the server's public key.
// Used for both E = Enc(PKs, B⊕R) and ED = Enc(PKs, D).
std::vector<uint8_t> EncryptWithServerPubKey(
    const std::vector<uint8_t>& plaintext) {
  EVP_PKEY* pub = internal::GetServerKeys().pub();

  internal::EvpPkeyCtxPtr ctx(EVP_PKEY_CTX_new(pub, nullptr));
  if (!ctx) throw std::runtime_error("EVP_PKEY_CTX_new failed");
  if (EVP_PKEY_encrypt_init(ctx.get()) != 1)
    throw std::runtime_error("EVP_PKEY_encrypt_init failed");
  if (EVP_PKEY_CTX_set_rsa_padding(ctx.get(), RSA_PKCS1_OAEP_PADDING) != 1)
    throw std::runtime_error("set_rsa_padding failed");
  if (EVP_PKEY_CTX_set_rsa_oaep_md(ctx.get(), EVP_sha256()) != 1)
    throw std::runtime_error("set_rsa_oaep_md failed");

  size_t outlen = 0;
  if (EVP_PKEY_encrypt(ctx.get(), nullptr, &outlen, plaintext.data(),
                       plaintext.size()) != 1)
    throw std::runtime_error("EVP_PKEY_encrypt (size query) failed");

  std::vector<uint8_t> ciphertext(outlen);
  if (EVP_PKEY_encrypt(ctx.get(), ciphertext.data(), &outlen, plaintext.data(),
                       plaintext.size()) != 1)
    throw std::runtime_error("EVP_PKEY_encrypt failed");

  ciphertext.resize(outlen);
  return ciphertext;
}

