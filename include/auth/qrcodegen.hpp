inline uint8_t gf_mul(uint8_t a, uint8_t b) {
  if (a == 0 || b == 0) return 0;
  int i = gf_log[a] + gf_log[b];
  if (i >= 255) i -= 255;
  return gf_exp[i];
}

std::vector<uint8_t> rsEncode(const std::vector<uint8_t>& data, int nsym) {
  // Generator polynomial has nsym+1 coefficients; remainder has nsym.
  std::vector<uint8_t> gen(nsym + 1, 0);
  gen[0] = 1;
  uint8_t x = 1;
  for (int i = 0; i < nsym; ++i) {
    for (int j = i + 1; j > 0; --j) {
      gen[j] = gf_mul(gen[j-1], x) ^ (j > 0 ? gen[j-1] : 0);
    }
    x = gf_mul(x, 2);
  }
  std::vector<uint8_t> rem(nsym, 0);
  for (uint8_t b : data) {
    uint8_t factor = b ^ rem[0];
    for (int j = 0; j < nsym - 1; ++j) {
      rem[j] = rem[j+1] ^ gf_mul(gen[nsym-1-j], factor);
    }
    rem[nsym-1] = gf_mul(gen[0], factor);
  }
  std::vector<uint8_t> ecc;
  for (int i = 0; i < nsym; ++i) ecc.push_back(rem[i]);
  return ecc;
}

inline void placeFinder(std::vector<std::vector<int>>& m, int row, int col) {
  for (int r = -1; r <= 7; ++r)
    for (int c = -1; c <= 7; ++c) {
      int rr = row + r, cc = col + c;
      if (rr < 0 || rr >= V40_SIZE || cc < 0 || cc >= V40_SIZE) continue;
      bool outer = r == 0 || r == 6 || c == 0 || c == 6;
      bool inner = r >= 2 && r <= 4 && c >= 2 && c <= 4;
      m[rr][cc] = (outer || inner) ? 1 : 0;
    }
}

inline void placeAlignment(std::vector<std::vector<int>>& m, int row, int col) {
  for (int r = -2; r <= 2; ++r)
    for (int c = -2; c <= 2; ++c) {
      int rr = row + r, cc = col + c;
      if (rr < 0 || rr >= V40_SIZE || cc < 0 || cc >= V40_SIZE) continue;
      bool edge = (r == -2 || r == 2 || c == -2 || c == 2);
      bool center = (r == 0 && c == 0);
      m[rr][cc] = (edge || center) ? 1 : 0;
    }
}

