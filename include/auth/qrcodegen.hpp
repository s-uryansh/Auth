inline std::vector<int> encode(const std::vector<uint8_t>& data) {
  std::vector<uint8_t> codewords;
  codewords.push_back(4);
  codewords.push_back((uint8_t)(data.size() >> 8));
  codewords.push_back((uint8_t)(data.size() & 0xff));
  for (auto b : data) codewords.push_back(b);
  static const uint8_t pads[] = {0xec, 0x11};
  int pi = 0;
  while ((int)codewords.size() < V40_DATA_BYTES) {
    codewords.push_back(pads[pi++ % 2]);
  }
  codewords.resize(V40_DATA_BYTES);

  auto ecc = rsEncode(codewords, V40_ECC_BYTES);
  std::vector<uint8_t> all;
  all.reserve(V40_DATA_BYTES + V40_ECC_BYTES);
  for (auto b : codewords) all.push_back(b);
  for (auto b : ecc) all.push_back(b);

  std::vector<std::vector<int>> modules(V40_SIZE, std::vector<int>(V40_SIZE, 0));
  std::vector<bool> reserved(V40_SIZE * V40_SIZE, false);

  placeFinder(modules, 0, 0);
  placeFinder(modules, V40_SIZE - 7, 0);
  placeFinder(modules, 0, V40_SIZE - 7);
  for (int i = 0; i < V40_SIZE; ++i) {
    if (i < 9) for (int j = 0; j < 9; ++j) reserved[i*V40_SIZE+j] = true;
    if (i < 9) for (int j = V40_SIZE-8; j < V40_SIZE; ++j) reserved[i*V40_SIZE+j] = true;
    if (i >= V40_SIZE-8) for (int j = 0; j < 9; ++j) reserved[i*V40_SIZE+j] = true;
    if (i >= V40_SIZE-8) for (int j = V40_SIZE-8; j < V40_SIZE; ++j) reserved[i*V40_SIZE+j] = true;
  }

  for (int i = 8; i < V40_SIZE - 8; ++i) {
    int v = (i % 2 == 0) ? 1 : 0;
    modules[6][i] = v; reserved[6*V40_SIZE + i] = true;
    modules[i][6] = v; reserved[i*V40_SIZE + 6] = true;
  }

  const int alignPos[] = {6, 22, 38, 54, 70, 86, 102, 118, 134, 150, 166};
  for (int r : alignPos)
    for (int c : alignPos) {
      if ((r < 9 && c < 9) || (r < 9 && c >= V40_SIZE - 8) || (r >= V40_SIZE - 8 && c < 9)) continue;
      placeAlignment(modules, r, c);
    }

  modules[V40_SIZE - 8][8] = 1;
  reserved[(V40_SIZE - 8)*V40_SIZE + 8] = true;

  for (int i = 0; i < 8; ++i) {
    reserved[8*V40_SIZE + i] = true;
    reserved[i*V40_SIZE + 8] = true;
    reserved[8*V40_SIZE + V40_SIZE - 1 - i] = true;
    reserved[(V40_SIZE - 1 - i)*V40_SIZE + 8] = true;
  }
  reserved[V40_SIZE * V40_SIZE - 9] = true;

  std::string bits;
  for (auto b : all) for (int i = 7; i >= 0; --i) bits.push_back(((b >> i) & 1) ? '1' : '0');
  int bitIdx = 0;
  bool upward = true;
  for (int col = V40_SIZE - 1; col >= 0; col -= 2) {
    if (col == 6) col = 5;
    for (int row = 0; row < V40_SIZE; ++row) {
      int r = upward ? V40_SIZE - 1 - row : row;
      for (int c = 0; c < 2; ++c) {
        int cc = col - c;
        if (cc < 0) continue;
        if (!reserved[r*V40_SIZE + cc]) {
          modules[r][cc] = bitIdx < (int)bits.size() ? (bits[bitIdx++] - '0') : 0;
        }
      }
    }
    upward = !upward;
  }

  for (int r = 0; r < V40_SIZE; ++r)
    for (int c = 0; c < V40_SIZE; ++c)
      if (!reserved[r*V40_SIZE + c] && (r + c) % 2 == 0)
        modules[r][c] ^= 1;

  const int fmt = 0x077C;
  for (int i = 0; i < 15; ++i) {
    bool bit = (fmt >> i) & 1;
    modules[8][i] = bit;
    modules[i][8] = bit;
  }
  for (int i = 0; i < 15; ++i) {
    bool bit = (fmt >> i) & 1;
    modules[V40_SIZE - 1 - i][8] = bit;
    modules[8][V40_SIZE - 1 - i] = bit;
  }

  std::vector<int> out(V40_SIZE * V40_SIZE);
  for (int i = 0; i < V40_SIZE; ++i)
    for (int j = 0; j < V40_SIZE; ++j)
      out[i*V40_SIZE + j] = modules[i][j];
  return out;
}

